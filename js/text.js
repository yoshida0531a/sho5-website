// Plain-text helpers shared by the static pages and Node tests.
// Entity decoding is one pass so decoded text can be assigned with textContent.

export function decodeBasicEntities(value) {
  return String(value ?? '')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, '&');
}
